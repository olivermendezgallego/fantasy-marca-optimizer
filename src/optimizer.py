def GreedyAlgorithmC(df_in, capital, max_jugadores=25, max_por_equipo=3):
    df = df_in.copy()
    df['ROI_diario'] = df['price_change'] / df['price']
    df = df.sort_values(by='ROI_diario', ascending=False)

    compras = []
    gasto_total = 0
    conteo_equipos = {}

    for _, player in df.iterrows():
        if player['price_change'] <= 0:
            continue
        if len(compras) >= max_jugadores:
            break  # ya no caben más, sea cual sea el ROI del resto
        if gasto_total + player['price'] > capital:
            continue

        equipo = player['team_id']
        if conteo_equipos.get(equipo, 0) >= max_por_equipo:
            continue

        compras.append(player)
        gasto_total += player['price']
        conteo_equipos[equipo] = conteo_equipos.get(equipo, 0) + 1

    return pd.DataFrame(compras)

