import pulp

def OptimalAlgorithm(df_in, capital, max_jugadores=25, max_por_equipo=3):
    df = df_in.reset_index(drop=True)
    prob = pulp.LpProblem("fantasy_optimo", pulp.LpMaximize)

    # una variable binaria por jugador: 1 si lo compras, 0 si no
    x = [pulp.LpVariable(f"x_{i}", cat="Binary") for i in df.index]

    # objetivo: maximizar la suma de revalorizaciones esperadas
    prob += pulp.lpSum(df.loc[i, "price_change"] * x[i] for i in df.index)

    # restricción de presupuesto
    prob += pulp.lpSum(df.loc[i, "price"] * x[i] for i in df.index) <= capital

    # restricción de plantilla máxima
    prob += pulp.lpSum(x[i] for i in df.index) <= max_jugadores

    # restricción de máximo N por equipo real
    for equipo in df["team_id"].dropna().unique():
        idx_equipo = df[df["team_id"] == equipo].index
        prob += pulp.lpSum(x[i] for i in idx_equipo) <= max_por_equipo

    prob.solve(pulp.PULP_CBC_CMD(msg=0))

    seleccionados = [i for i in df.index if x[i].value() == 1]
    return df.loc[seleccionados]

